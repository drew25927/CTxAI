// 아트 월드 도로의 중앙선(노란선 메시, .blend "Faded centre line")을 /film 좌표 (x, z)로 4m 간격 샘플한 것.
// 도로가 휘어 있어서(x −48 에서 z −1.8, x +28 에서 z −9.6) 직선으로 달리면 트럭·버스가 길 밖으로 나간다 — 이 선을 따른다.
export const ART_ROAD_CENTER = [[-88, 8.86], [-84, 7.51], [-80, 6.22], [-76, 4.99], [-72, 3.83], [-68, 2.74], [-64, 1.71], [-60, 0.74], [-56, -0.17], [-52, -1.01], [-48, -1.78], [-44, -2.49], [-40, -3.14], [-36, -3.73], [-32, -4.25], [-28, -4.7], [-24, -5.1], [-20, -5.42], [-16, -5.69], [-12, -5.89], [-8, -6.02], [-4, -6.09], [0, -6.12], [4, -6.24], [8, -6.48], [12, -6.84], [16, -7.34], [20, -7.96], [24, -8.72], [28, -9.6], [32, -10.6], [36, -11.74], [40, -13.0], [44, -14.4], [48, -15.92], [52, -17.48], [56, -19.11], [60, -21.0], [64, -23.02], [68, -25.16], [72, -27.43], [76, -29.83], [80, -32.36], [84, -34.46]];
const NEAR_LANE_OFFSET = 1.8; // 중앙선에서 관객 쪽(+z)으로 차선 반폭 — x=0 에서 가까운 차선 중앙 z −4.3

export function roadCenter(x) { return centerAt(x); }

function centerAt(x) {
  const p = ART_ROAD_CENTER;
  if (x <= p[0][0]) return p[0][1];
  for (let i = 1; i < p.length; i++) {
    if (x <= p[i][0]) { const f = (x - p[i - 1][0]) / (p[i][0] - p[i - 1][0]); return p[i - 1][1] + (p[i][1] - p[i - 1][1]) * f; }
  }
  return p[p.length - 1][1];
}

/** 가까운 차선 중앙의 z 와 진행 기울기 dz/dx. */
export function nearLane(x) {
  return { z: centerAt(x) + NEAR_LANE_OFFSET, slope: (centerAt(x + 1) - centerAt(x - 1)) / 2 };
}
